// 페이지 slug → 제도 id 매핑 (GovSupport.astro에서 사용)
export function programsForPage(slug) {
  return PROGRAMS.filter((p) => p.pages.includes(slug));
}

// 소득 판정: 연봉(만원), 가구원수 → { eligible, reason, cap }
// cap은 판정 기준이 된 연봉 상한(만원), 기준이 없으면 null
export function judgeIncome(program, salaryManwon, household) {
  const t = program.income.type;
  if (t === 'none') {
    return { eligible: true, reason: '소득 기준 없음', cap: null };
  }
  if (t === 'median') {
    const base = MEDIAN_INCOME_2026[Math.min(household, 6)] || MEDIAN_INCOME_2026[4];
    const cap = Math.floor((base * program.income.percent) / 100 / 10000);
    if (salaryManwon <= cap) {
      return { eligible: true, reason: `중위소득 ${program.income.percent}% 이하 충족`, cap };
    }
    return { eligible: false, reason: `소득 기준 초과 (연봉 약 ${cap.toLocaleString('ko-KR')}만원 이하)`, cap };
  }
  // salaryCap
  const cap = program.income.amount;
  if (salaryManwon <= cap) {
    return { eligible: true, reason: `연봉 ${cap.toLocaleString('ko-KR')}만원 이하 충족`, cap };
  }
  return { eligible: false, reason: `소득 기준 초과 (연봉 ${cap.toLocaleString('ko-KR')}만원 이하)`, cap };
}
